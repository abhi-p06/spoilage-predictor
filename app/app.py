"""
app.py
======
Flask web application entry point for the Post-Harvest Spoilage Predictor.

Routes
------
GET  /          → Input form (index.html)
POST /predict   → Runs all three models and renders the result dashboard
GET  /report    → Returns a plain-text .txt download of the last prediction

Usage
-----
  cd app/
  python app.py
  # or from project root:
  flask --app app/app.py run --debug
"""

import json
from datetime import datetime
from pathlib import Path

from flask import Flask, render_template, request, redirect, url_for, send_file, session
from werkzeug.utils import secure_filename

from predict import run_prediction

# ── Flask setup ───────────────────────────────────────────────────────────────
BASE_DIR   = Path(__file__).parent
UPLOAD_DIR = BASE_DIR / "static" / "uploads"
UPLOAD_DIR.mkdir(parents=True, exist_ok=True)

ALLOWED_EXT = {"jpg", "jpeg", "png", "webp"}

app = Flask(__name__)
app.secret_key = "spoilage-predictor-secret-2024"   # needed for session
app.config["MAX_CONTENT_LENGTH"] = 16 * 1024 * 1024  # 16 MB upload limit


# ── Helpers ───────────────────────────────────────────────────────────────────

def allowed_file(filename: str) -> bool:
    """Return True if the file extension is in the allowed set."""
    return "." in filename and filename.rsplit(".", 1)[1].lower() in ALLOWED_EXT


# ── Routes ────────────────────────────────────────────────────────────────────

@app.route("/", methods=["GET"])
def index():
    """Render the input form."""
    return render_template("index.html")


@app.route("/predict", methods=["POST"])
def predict():
    """
    Accept form submission, run the three-model pipeline, and render results.

    Form fields expected
    --------------------
    image       : uploaded fruit/vegetable photo
    produce     : apple | banana | tomato | mango
    days        : int  (days since harvest)
    cold_chain  : yes | no
    """
    # ── Validate image upload ─────────────────────────────────────────────────
    if "image" not in request.files:
        return redirect(url_for("index"))

    file = request.files["image"]
    if file.filename == "" or not allowed_file(file.filename):
        return redirect(url_for("index"))

    # ── Save uploaded image ───────────────────────────────────────────────────
    filename  = secure_filename(file.filename)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    save_name = f"{timestamp}_{filename}"
    save_path = UPLOAD_DIR / save_name
    file.save(save_path)

    # ── Parse form inputs ─────────────────────────────────────────────────────
    produce    = request.form.get("produce",    "apple").lower()
    days       = int(request.form.get("days",   3))
    cold_chain = request.form.get("cold_chain", "no").lower() == "yes"

    # ── Run prediction pipeline ───────────────────────────────────────────────
    result = run_prediction(
        image_path  = save_path,
        produce     = produce,
        days        = days,
        cold_chain  = cold_chain,
    )

    # Add UI metadata to result
    result["image_url"]  = f"uploads/{save_name}"
    result["produce"]    = produce.capitalize()
    result["days"]       = days
    result["cold_chain"] = "Yes" if cold_chain else "No"
    result["timestamp"]  = datetime.now().strftime("%d %b %Y, %H:%M")

    # Persist result in session for the /report download route
    session["last_result"] = json.dumps(result)

    return render_template("result.html", r=result)


@app.route("/report")
def report():
    """Generate and download a plain-text summary of the last prediction."""
    raw = session.get("last_result")
    if not raw:
        return redirect(url_for("index"))

    r = json.loads(raw)

    lines = [
        "=" * 60,
        "  POST-HARVEST SPOILAGE PREDICTOR — ANALYSIS REPORT",
        "=" * 60,
        f"  Generated : {r.get('timestamp', 'N/A')}",
        f"  Produce   : {r.get('produce', 'N/A')}",
        "",
        "  PREDICTION RESULTS",
        "  " + "-" * 40,
        f"  Alert Level          : {r.get('alert', 'N/A')}",
        f"  Spoilage Probability : {r.get('spoilage_pct', 0):.1f}%",
        f"  Days to Spoilage     : {r.get('days_to_spoilage', 0)} days",
        f"  CNN Freshness Score  : {r.get('cnn_score_pct', 0):.1f}%",
        f"  Sensor Risk Score    : {r.get('lstm_score_pct', 0):.1f}%",
        "",
        "  INPUT DETAILS",
        "  " + "-" * 40,
        f"  Days Since Harvest   : {r.get('days', 'N/A')}",
        f"  Cold Chain Storage   : {r.get('cold_chain', 'N/A')}",
        f"  Typical Shelf Life   : {r.get('shelf_life', 'N/A')} days",
        "",
        "  RECOMMENDATION",
        "  " + "-" * 40,
        f"  {r.get('recommendation', 'N/A')}",
        "",
        "=" * 60,
        "  This report was generated by the Spoilage Predictor AI system.",
        "  For research and educational use only.",
        "=" * 60,
    ]

    txt_content = "\n".join(lines)
    report_path = UPLOAD_DIR / f"report_{r.get('timestamp', 'report').replace(' ', '_').replace(',', '')}.txt"
    report_path.write_text(txt_content)

    return send_file(report_path, as_attachment=True, download_name="spoilage_report.txt")


# ── Entry point ───────────────────────────────────────────────────────────────

if __name__ == "__main__":
    app.run(debug=True, port=5000)
